"use client";
import React, { createContext, useContext, useState, useCallback, useEffect, useRef, ReactNode } from "react";

// --- Types ---

export type MapType = "payment_status" | "overdue_status";

export interface MapContextData {
  map_type: MapType;
  year: string;
  zoom_level: number;
  bounds?: { north: number; south: number; east: number; west: number } | null;
  active_region?: string | null;
  kecamatan?: string | null;
  last_clicked_nop?: string | null;
}

export interface ChatMessage {
  id: string;
  role: "user" | "assistant";
  content: string;
  timestamp: Date;
  isStreaming?: boolean;
}

export interface MapCommand {
  action: "navigate" | "highlight" | "navigate_and_highlight" | "clear_highlights";
  targets?: Array<{
    code?: string;
    lat?: number;
    lng?: number;
    geometry?: GeoJSON.Geometry;
  }>;
  zoom_level?: number;
  highlight_color?: string;
  // "proactive" means the highlight was auto-generated by the briefing.
  // The frontend auto-clears proactive highlights after a short timer so the
  // map doesn't stay cluttered. Explicit user commands (source absent/"user")
  // persist until the user clears them.
  source?: "proactive" | "user";
  // When present, the NOP detail panel should open (same as a user clicking
  // the persil). 18-digit NOP, no separators.
  open_detail_nop?: string;
}

interface AICopilotContextValue {
  // State
  isCopilotOpen: boolean;
  messages: ChatMessage[];
  isLoading: boolean;
  isBriefingLoading: boolean;
  queuedCount: number;
  sessionId: string | null;
  currentBriefing: string | null;
  mapContext: MapContextData | null;

  // Map command queue
  pendingMapCommand: MapCommand | null;
  clearPendingMapCommand: () => void;

  // Actions
  toggleCopilot: () => void;
  openCopilot: () => void;
  closeCopilot: () => void;
  sendMessage: (message: string) => Promise<void>;
  requestBriefing: (override?: MapContextData) => Promise<void>;
  clearSession: () => void;
  updateMapContext: (ctx: MapContextData) => void;
}

const AICopilotContext = createContext<AICopilotContextValue | undefined>(undefined);

const AI_API_URL = process.env.NEXT_PUBLIC_AI_API_URL;

// FastAPI can return `detail` as a string OR an array of validation-error
// objects (e.g. `[{loc, msg, type}]`). The raw array stringifies to
// "[object Object]", so we normalize it to a readable message.
function formatErrorDetail(detail: unknown): string {
  if (!detail) return "";
  if (typeof detail === "string") return detail;
  if (Array.isArray(detail)) {
    return detail
      .map((d) => {
        if (typeof d === "string") return d;
        if (d && typeof d === "object") {
          const rec = d as Record<string, unknown>;
          if (typeof rec.msg === "string") return rec.msg;
        }
        return "";
      })
      .filter(Boolean)
      .join("; ") || "Permintaan tidak valid";
  }
  if (typeof detail === "object") {
    const rec = detail as Record<string, unknown>;
    if (typeof rec.msg === "string") return rec.msg;
    try {
      return JSON.stringify(detail);
    } catch {
      return "Terjadi kesalahan";
    }
  }
  return String(detail);
}

interface AICopilotProviderProps {
  children: ReactNode;
}

export function AICopilotProvider({ children }: AICopilotProviderProps) {
  const [isCopilotOpen, setIsCopilotOpen] = useState(false);
  const [messages, setMessages] = useState<ChatMessage[]>([]);
  const [isLoading, setIsLoading] = useState(false);
  const [isBriefingLoading, setIsBriefingLoading] = useState(false);
  const [sessionId, setSessionId] = useState<string | null>(null);
  const [currentBriefing, setCurrentBriefing] = useState<string | null>(null);
  const [mapContext, setMapContext] = useState<MapContextData | null>(null);
  const [pendingMapCommand, setPendingMapCommand] = useState<MapCommand | null>(null);
  const [queuedCount, setQueuedCount] = useState(0);
  const abortControllerRef = useRef<AbortController | null>(null);
  const streamingRef = useRef(false);
  const queueRef = useRef<string[]>([]);
  const runSendRef = useRef<((message: string) => Promise<void>) | null>(null);

  // Send the next queued message (if any) once the active stream has ended.
  const flushQueue = useCallback(() => {
    if (queueRef.current.length === 0) return;
    const next = queueRef.current.shift() as string;
    setQueuedCount(queueRef.current.length);
    void runSendRef.current?.(next);
  }, []);

  const toggleCopilot = useCallback(() => setIsCopilotOpen((prev) => !prev), []);
  const openCopilot = useCallback(() => setIsCopilotOpen(true), []);
  const closeCopilot = useCallback(() => setIsCopilotOpen(false), []);
  const clearPendingMapCommand = useCallback(() => setPendingMapCommand(null), []);

  const updateMapContext = useCallback((ctx: MapContextData) => {
    setMapContext(ctx);
  }, []);

  const clearSession = useCallback(() => {
    setMessages([]);
    setSessionId(null);
    setCurrentBriefing(null);
  }, []);

  const processSSEStream = useCallback(
    async (
      response: Response,
      onText: (text: string) => void,
      onDone?: (usage: { input_tokens: number; output_tokens: number }, cost: number) => void
    ) => {
      const reader = response.body?.getReader();
      if (!reader) return;

      const decoder = new TextDecoder();
      let buffer = "";

      try {
        while (true) {
          const { done, value } = await reader.read();
          if (done) break;

          buffer += decoder.decode(value, { stream: true });
          const lines = buffer.split("\n");
          buffer = lines.pop() || "";

          for (const line of lines) {
            if (!line.startsWith("data: ")) continue;
            const jsonStr = line.slice(6).trim();
            if (!jsonStr) continue;

            try {
              const data = JSON.parse(jsonStr);

              if (data.type === "session_id" && data.session_id) {
                setSessionId(data.session_id);
              } else if (data.type === "text_delta" && data.content) {
                onText(data.content);
              } else if (data.type === "map_command" && data.map_command) {
                console.log("[AICopilot] received map_command from SSE:", data.map_command);
                setPendingMapCommand(data.map_command as MapCommand);
              } else if (data.type === "done") {
                onDone?.(data.usage || {}, data.cost_usd || 0);
              } else if (data.type === "error") {
                onText(`\n\n_Error: ${formatErrorDetail(data.error) || "Terjadi kesalahan"}_`);
              }
            } catch {
              // Skip malformed JSON
            }
          }
        }
      } finally {
        reader.releaseLock();
      }
    },
    []
  );

  const runSend = useCallback(
    async (message: string) => {
      abortControllerRef.current?.abort();
      const abortController = new AbortController();
      abortControllerRef.current = abortController;
      streamingRef.current = true;

      // Add user message
      const userMsg: ChatMessage = {
        id: `user_${Date.now()}`,
        role: "user",
        content: message.trim(),
        timestamp: new Date(),
      };

      // Add placeholder assistant message
      const assistantMsgId = `assistant_${Date.now()}`;
      const assistantMsg: ChatMessage = {
        id: assistantMsgId,
        role: "assistant",
        content: "",
        timestamp: new Date(),
        isStreaming: true,
      };

      setMessages((prev) => [...prev, userMsg, assistantMsg]);
      setIsLoading(true);

      try {
        const response = await fetch(`${AI_API_URL}/ai/copilot/chat`, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          credentials: "include",
          signal: abortController.signal,
          body: JSON.stringify({
            message: message.trim(),
            session_id: sessionId,
            map_context: mapContext,
          }),
        });

        if (!response.ok) {
          const errData = await response.json().catch(() => ({ detail: "Terjadi kesalahan" }));
          const detailText = formatErrorDetail(errData?.detail) || "Terjadi kesalahan";
          setMessages((prev) =>
            prev.map((m) =>
              m.id === assistantMsgId
                ? { ...m, content: `_Error: ${detailText}_`, isStreaming: false }
                : m
            )
          );
          setIsLoading(false);
          return;
        }

        await processSSEStream(
          response,
          (text) => {
            setMessages((prev) =>
              prev.map((m) => (m.id === assistantMsgId ? { ...m, content: m.content + text } : m))
            );
          },
          () => {
            setMessages((prev) =>
              prev.map((m) => (m.id === assistantMsgId ? { ...m, isStreaming: false } : m))
            );
          }
        );
      } catch (err) {
        if ((err as Error).name !== "AbortError") {
          setMessages((prev) =>
            prev.map((m) =>
              m.id === assistantMsgId
                ? { ...m, content: "_Gagal menghubungi AI Service. Silakan coba lagi._", isStreaming: false }
                : m
            )
          );
        }
      } finally {
        setMessages((prev) =>
          prev.map((m) =>
            m.id === assistantMsgId ? { ...m, isStreaming: false } : m
          )
        );
        if (abortControllerRef.current === abortController) {
          streamingRef.current = false;
          setIsLoading(false);
          flushQueue();
        }
      }
    },
    [mapContext, sessionId, processSSEStream, flushQueue]
  );
  runSendRef.current = runSend;

  // Public send: while a stream is in flight, queue the message so it auto-sends
  // when the current stream finishes, instead of aborting (truncating) it.
  const sendMessage = useCallback(
    async (message: string) => {
      const text = message.trim();
      if (!text || !mapContext) return;
      if (streamingRef.current) {
        queueRef.current.push(text);
        setQueuedCount(queueRef.current.length);
        return;
      }
      await runSend(text);
    },
    [mapContext, runSend]
  );

  const requestBriefing = useCallback(async (override?: MapContextData) => {
    const ctxToUse = override ?? mapContext;
    if (!ctxToUse) return;

    abortControllerRef.current?.abort();
    const abortController = new AbortController();
    abortControllerRef.current = abortController;
    streamingRef.current = true;

    setIsLoading(true);
    setIsBriefingLoading(true);
    setCurrentBriefing("");

    try {
      const response = await fetch(`${AI_API_URL}/ai/copilot/briefing`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        credentials: "include",
        signal: abortController.signal,
        body: JSON.stringify({
          map_context: ctxToUse,
          session_id: sessionId,
        }),
      });

      if (!response.ok) {
        setCurrentBriefing("_Gagal memuat briefing._");
        setIsLoading(false);
        setIsBriefingLoading(false);
        return;
      }

      let briefingText = "";
      await processSSEStream(
        response,
        (text) => {
          briefingText += text;
          setCurrentBriefing(briefingText);
        },
      );
    } catch (err) {
      if ((err as Error).name !== "AbortError") {
        setCurrentBriefing("_Gagal menghubungi AI Service._");
      }
    } finally {
      if (abortControllerRef.current === abortController) {
        streamingRef.current = false;
        setIsLoading(false);
        setIsBriefingLoading(false);
        flushQueue();
      }
    }
  }, [mapContext, sessionId, processSSEStream, flushQueue]);

  // Auto-trigger briefing whenever a new map layer is activated.
  // updateMapContext is only invoked on layer activation (not zoom/pan),
  // so reacting to map_type/year/kecamatan changes is the right granularity.
  const briefedKeyRef = useRef<string | null>(null);
  useEffect(() => {
    if (!mapContext) {
      briefedKeyRef.current = null;
      return;
    }
    const key = `${mapContext.map_type}:${mapContext.year}:${mapContext.kecamatan ?? "all"}`;
    if (briefedKeyRef.current === key) return;
    briefedKeyRef.current = key;
    setIsCopilotOpen(true);
    void requestBriefing(mapContext);
  }, [mapContext, requestBriefing]);

  const value: AICopilotContextValue = {
    isCopilotOpen,
    messages,
    isLoading,
    isBriefingLoading,
    queuedCount,
    sessionId,
    currentBriefing,
    mapContext,
    pendingMapCommand,
    clearPendingMapCommand,
    toggleCopilot,
    openCopilot,
    closeCopilot,
    sendMessage,
    requestBriefing,
    clearSession,
    updateMapContext,
  };

  return <AICopilotContext.Provider value={value}>{children}</AICopilotContext.Provider>;
}

export function useAICopilot(): AICopilotContextValue {
  const context = useContext(AICopilotContext);
  if (context === undefined) {
    throw new Error("useAICopilot must be used within an AICopilotProvider");
  }
  return context;
}
